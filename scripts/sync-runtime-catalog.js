#!/usr/bin/env node
/**
 * Vendors the runtime catalog snapshot the offline bundler checks imports
 * against (`RUNTIME_CATALOG` in `@devhelm/sdk/bundler`).
 *
 * Usage: node scripts/sync-runtime-catalog.js <mono>/api/src/main/resources/synthetics/runtime-catalog.json
 *
 * Online callers refresh it from GET /api/v1/synthetics/runtime-profiles/{id}.
 */
import {readFileSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const input = process.argv[2]
if (!input) {
  console.error('usage: node scripts/sync-runtime-catalog.js <runtime-catalog.json>')
  process.exit(1)
}
const catalog = JSON.parse(readFileSync(input, 'utf8'))
const runtimes = catalog.runtimes.map((r) => ({
  id: r.id,
  status: r.status,
  nodeVersion: r.nodeVersion,
  playwrightVersion: r.playwrightVersion,
  eolAt: r.eolAt ?? null,
  packages: r.packages,
  nodeBuiltins: r.nodeBuiltins,
}))
const out = join(ROOT, 'src/bundler/runtime-catalog.generated.ts')
writeFileSync(
  out,
  '// Auto-generated by scripts/sync-runtime-catalog.js from the API runtime catalog. DO NOT EDIT.\n' +
    "import type {RuntimePackages} from './runtime.js'\n\n" +
    `export const RUNTIME_CATALOG_SOURCE = ${JSON.stringify(catalog.source ?? '')}\n\n` +
    `export const RUNTIME_CATALOG: ReadonlyArray<RuntimePackages> = ${JSON.stringify(runtimes, null, 2)}\n`,
)
console.log(`Done: ${runtimes.length} runtimes → ${out}`)
